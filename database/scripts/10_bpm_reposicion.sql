CREATE OR REPLACE VIEW SIGEFER_APP.VW_BPM_REPOSICION AS
SELECT
    solicitud.ID_SOLICITUD,
    solicitud.NUMERO_SOLICITUD,

    solicitud.ID_PRODUCTO,
    producto.CODIGO AS CODIGO_PRODUCTO,
    producto.NOMBRE AS PRODUCTO,
    producto.UNIDAD_MEDIDA,

    solicitud.ID_PROVEEDOR,
    proveedor.RUC AS RUC_PROVEEDOR,
    proveedor.RAZON_SOCIAL AS PROVEEDOR,

    solicitud.ID_ALERTA,
    alerta.TIPO_ALERTA,
    alerta.ESTADO AS ESTADO_ALERTA,

    solicitud.CANTIDAD_SOLICITADA,
    solicitud.CANTIDAD_RECIBIDA,

    solicitud.COSTO_UNITARIO_ESTIMADO,
    solicitud.COSTO_TOTAL_ESTIMADO,

    solicitud.ESTADO,

    inventario.STOCK_ACTUAL,
    inventario.STOCK_RESERVADO,
    inventario.STOCK_DISPONIBLE,
    producto.STOCK_MINIMO,

    solicitud.ID_USUARIO_SOLICITANTE,
    usuario_solicitante.NOMBRE_USUARIO
        AS USUARIO_SOLICITANTE,

    solicitud.ID_USUARIO_APROBADOR,
    usuario_aprobador.NOMBRE_USUARIO
        AS USUARIO_APROBADOR,

    solicitud.ID_USUARIO_RECEPTOR,
    usuario_receptor.NOMBRE_USUARIO
        AS USUARIO_RECEPTOR,

    solicitud.FECHA_SOLICITUD,
    solicitud.FECHA_APROBACION,
    solicitud.FECHA_RECHAZO,
    solicitud.FECHA_PEDIDO,
    solicitud.FECHA_RECEPCION,
    solicitud.FECHA_CIERRE,

    solicitud.OBSERVACION,
    solicitud.MOTIVO_RECHAZO,

    solicitud.FECHA_CREACION,
    solicitud.FECHA_ACTUALIZACION

FROM SIGEFER_APP.SOLICITUD_REPOSICION solicitud

INNER JOIN SIGEFER_APP.PRODUCTO producto
    ON producto.ID_PRODUCTO =
        solicitud.ID_PRODUCTO

INNER JOIN SIGEFER_APP.PROVEEDOR proveedor
    ON proveedor.ID_PROVEEDOR =
        solicitud.ID_PROVEEDOR

INNER JOIN SIGEFER_APP.INVENTARIO inventario
    ON inventario.ID_PRODUCTO =
        solicitud.ID_PRODUCTO

INNER JOIN SIGEFER_APP.USUARIO usuario_solicitante
    ON usuario_solicitante.ID_USUARIO =
        solicitud.ID_USUARIO_SOLICITANTE

LEFT JOIN SIGEFER_APP.USUARIO usuario_aprobador
    ON usuario_aprobador.ID_USUARIO =
        solicitud.ID_USUARIO_APROBADOR

