                    GENERATED ALWAYS AS (
                        ROUND(
                            CANTIDAD_SOLICITADA
                            * COSTO_UNITARIO_ESTIMADO,
                            2
                        )
                    ) VIRTUAL,

                ESTADO VARCHAR2(15)
                    DEFAULT 'BORRADOR' NOT NULL,

