DECLARE
    PROCEDURE crear_tabla_si_falta(
        p_nombre VARCHAR2,
        p_ddl    VARCHAR2
    ) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_count
        FROM ALL_TABLES
        WHERE OWNER = 'SIGEFER_APP'
          AND TABLE_NAME = UPPER(p_nombre);

        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;

            DBMS_OUTPUT.PUT_LINE(
                'Tabla ' || UPPER(p_nombre) || ' creada.'
            );
        ELSE
            DBMS_OUTPUT.PUT_LINE(
                'Tabla ' || UPPER(p_nombre) || ' ya existe.'
            );
        END IF;
    END;

    PROCEDURE crear_indice_si_falta(
        p_nombre VARCHAR2,
        p_ddl    VARCHAR2
    ) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_count
        FROM ALL_INDEXES
        WHERE OWNER = 'SIGEFER_APP'
          AND INDEX_NAME = UPPER(p_nombre);

        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;

            DBMS_OUTPUT.PUT_LINE(
                'Indice ' || UPPER(p_nombre) || ' creado.'
            );
        ELSE
            DBMS_OUTPUT.PUT_LINE(
                'Indice ' || UPPER(p_nombre) || ' ya existe.'
            );
        END IF;
    END;
