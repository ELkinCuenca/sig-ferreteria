MERGE INTO SIGEFER_APP.IOT_DISPOSITIVO destino
USING (
    SELECT
        'BODEGA-01' AS CODIGO
    FROM DUAL
) origen
ON (
    destino.CODIGO = origen.CODIGO
)
WHEN NOT MATCHED THEN
    INSERT (
        CODIGO,
        NOMBRE,
        UBICACION,
        TOPICO_TELEMETRIA,
        TIPO_SENSOR,
        ESTADO
    )
    VALUES (
        'BODEGA-01',
        'Sensor ambiental de bodega',
        'BODEGA PRINCIPAL',
        'sigefer/iot/bodega-01/telemetria',
        'ESP32_DHT11',
        'A'
    );

MERGE INTO SIGEFER_APP.IOT_CONFIGURACION destino
USING (
    SELECT
        ID_DISPOSITIVO
    FROM SIGEFER_APP.IOT_DISPOSITIVO
    WHERE CODIGO = 'BODEGA-01'
) origen
ON (
    destino.ID_DISPOSITIVO =
        origen.ID_DISPOSITIVO
)
WHEN NOT MATCHED THEN
    INSERT (
        ID_DISPOSITIVO,
        TEMPERATURA_MIN_C,
        TEMPERATURA_MAX_C,
        HUMEDAD_MIN_PCT,
        HUMEDAD_MAX_PCT,
        SEGUNDOS_SIN_COMUNICACION,
        ESTADO
    )
    VALUES (
        origen.ID_DISPOSITIVO,
        10,
        30,
        25,
        70,
        120,
        'A'
    );

